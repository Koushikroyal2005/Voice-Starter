// Mechanical generation only; schemas remain the sole wire-contract source.
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'contracts/voice-workbench/v1');
const destination = path.join(root, 'lib/workbench/generated');
const events = JSON.parse(await readFile(path.join(source, 'events.schema.json'), 'utf8'));
const rpc = JSON.parse(await readFile(path.join(source, 'rpc.schema.json'), 'utf8'));
// This catalog is generation metadata, not another on-wire schema/envelope.
const catalog = {
  title: 'WorkbenchContracts',
  type: 'object',
  additionalProperties: false,
  required: ['event', 'rpc', 'error', 'cardType', 'resultData'],
  properties: {
    event: { $ref: 'events.schema.json' },
    rpc: { $ref: 'rpc.schema.json' },
    error: { $ref: 'rpc.schema.json#/$defs/rpcError' },
    cardType: { $ref: 'events.schema.json#/$defs/cardType' },
    resultData: { $ref: 'events.schema.json#/$defs/resultData' },
  },
};
const ajv = new Ajv2020({ code: { source: true }, inlineRefs: false, strictRequired: false });
ajv.addSchema(events).addSchema(rpc);
const refs = {
  validateEvent: events.$id,
  validateRpc: rpc.$id,
  validatePublicUseCase: `${rpc.$id}#/$defs/publicUseCase`,
  validateToolsState: `${rpc.$id}#/$defs/toolsState`,
  validateConfirmationRequest: `${rpc.$id}#/$defs/confirmationRequest`,
  validateAccepted: `${rpc.$id}#/$defs/accepted`,
  validateInterrupted: `${rpc.$id}#/$defs/interrupted`,
  validateEmptyRequest: `${rpc.$id}#/$defs/emptyRequest`,
  validateRpcError: `${rpc.$id}#/$defs/rpcError`,
  validateCardType: `${events.$id}#/$defs/cardType`,
  validateResultData: `${events.$id}#/$defs/resultData`,
};
for (const ref of Object.values(refs)) if (!ajv.getSchema(ref)) throw new Error('Missing contract');
const options = await prettier.resolveConfig(path.join(root, 'package.json'));
const format = (text, parser) =>
  prettier.format(text, { ...options, plugins: [], parser, endOfLine: 'lf' });
const types = await compile(catalog, 'WorkbenchContracts', {
  cwd: `${source}${path.sep}`,
  unknownAny: true,
  maxItems: -1,
  bannerComment: '// Generated by pnpm contracts:generate. Do not edit.',
  $refOptions: { resolve: { http: false } },
});
const outputs = {
  'types.ts': await format(
    types +
      `\nexport const WORKBENCH_TOPIC = ${JSON.stringify(events.$defs.topic.const)} as const;\n`,
    'typescript'
  ),
  'validators.cjs': await format(
    '// Generated by pnpm contracts:generate. Do not edit.\n' + standaloneCode(ajv, refs),
    'babel'
  ),
  'validators.d.cts': await format(
    Object.keys(refs)
      .map((name) => `export function ${name}(value: unknown): boolean;`)
      .join('\n'),
    'typescript'
  ),
};
if (!process.argv.includes('--check')) await mkdir(destination, { recursive: true });
for (const [name, output] of Object.entries(outputs)) {
  const target = path.join(destination, name);
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8').catch(() => '')) !== output)
      throw new Error(`Stale generated contract: ${name}`);
  } else await writeFile(target, output);
}
process.stdout.write(
  process.argv.includes('--check')
    ? 'Contracts are current and schemas compile.\n'
    : 'Generated workbench types and standalone validators.\n'
);
